    #[test]
    fn reveal_scrolls_the_least_it_can_and_paging_moves_the_body() {
        let mut s = state();
        s.open(&TopicId::new("copying"));
        assert_eq!(s.body_scroll(), 0);

        // Already inside the window: nothing moves.
        s.reveal(3, 10);
        assert_eq!(s.body_scroll(), 0);
        // Below it: the line becomes the last one painted.
        s.reveal(12, 10);
        assert_eq!(s.body_scroll(), 3);
        // Above it: the line becomes the first one painted.
        s.reveal(1, 10);
        assert_eq!(s.body_scroll(), 1);
        // A window of zero lines has nothing to reveal into.
        s.reveal(99, 0);
        assert_eq!(s.body_scroll(), 1);
        // An absurd line number saturates instead of aborting the process:
        // the line count comes from a laid-out body, and arithmetic that only
        // holds for plausible bodies is arithmetic that panics one day.
        s.reveal(usize::MAX, 10);
        assert_eq!(s.body_scroll(), usize::MAX - 9);
        s.reveal(usize::MAX, usize::MAX);
        s.reveal(0, 10);
        assert_eq!(s.body_scroll(), 0);

        s.toggle_focus();
        assert_eq!(s.focus(), Focus::Body);
        let action = s.action_cursor();
        s.page_down(20);
        s.clamp_scroll(12);
        assert_eq!(
            s.body_scroll(),
            11,
            "the renderer says how many lines it laid out, and the scroll \
             stops at the last one"
        );
        assert_eq!(
            s.action_cursor(),
            action,
            "a page is a movement over prose, not over actions"
        );
        s.page_down(1_000_000);
        s.clamp_scroll(12);
        assert_eq!(s.body_scroll(), 11, "a huge page cannot outrun the body");
        s.clamp_scroll(0);
        assert_eq!(s.body_scroll(), 0, "a body with no lines has no scroll");
        s.page_up(100);
        assert_eq!(s.body_scroll(), 0, "paging past the top stops at the top");
    }

