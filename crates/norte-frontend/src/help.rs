    #[test]
    fn a_hostile_title_is_matched_on_its_raw_bytes() {
        let hostile = Topic {
            id: TopicId::new("hostile"),
            title: "cop\u{202E}y".to_owned(),
            tags: Vec::new(),
            see_also: Vec::new(),
            commands: Vec::new(),
            context: Vec::new(),
            blocks: Vec::new(),
            origin: norte_help::Origin::BuiltIn,
        };

        // The needle is folded, never masked — and neither is the haystack.
        // Folding either side through `mask_terminal_hazards` would replace
        // the override with a placeholder on ONE side only, and a title the
        // reader can see on screen would stop being findable by typing it.
        assert!(matches(&hostile, &fold("cop\u{202E}y".as_bytes())));
        assert!(
            !matches(
                &hostile,
                &fold(mask_terminal_hazards("cop\u{202E}y").as_bytes())
            ),
            "the masked spelling is a DIFFERENT string; it is what gets \
             painted, never what gets matched"
        );
        assert!(
            matches(&hostile, &fold(b"cop")),
            "the plain prefix still hits"
        );
    }
